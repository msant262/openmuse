import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const result = await build({
  entryPoints: [fileURLToPath(new URL("../src/avatar/native-entry.ts", import.meta.url))],
  bundle: true,
  minify: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: "es2020",
  legalComments: "inline",
});
const script = result.outputFiles[0].text;
const output = `// Generated by pnpm --dir apps/mobile build:avatar. Do not edit.\n// Includes locally bundled Three.js (MIT); see THIRD-PARTY-LICENSES.md.\n// biome-ignore-all format: generated bundle\n// biome-ignore-all lint/suspicious/noTemplateCurlyInString: bundled JavaScript source contains template strings\nexport const AVATAR_SCENE_SCRIPT = ${JSON.stringify(script)};\n`;
const target = new URL("../src/avatar/scene-bundle.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("Avatar bundle is stale. Run pnpm --dir apps/mobile build:avatar.");
  console.log("Local Android avatar bundle matches the shared scene.");
} else {
  await writeFile(target, output);
  console.log(`Bundled local 3D avatar scene (${Math.round(script.length / 1024)} KiB).`);
}
