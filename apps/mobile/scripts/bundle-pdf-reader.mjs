import { createHash } from "node:crypto";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

export async function bundlePdfReader({
  publicRoot = fileURLToPath(new URL("../public/_expo/static/pdf-reader", import.meta.url)),
  manifestPath = fileURLToPath(new URL("../src/pdf-reader-assets.ts", import.meta.url)),
} = {}) {
  const require = createRequire(import.meta.url);
  const root = dirname(require.resolve("pdfjs-dist/package.json"));
  const { version } = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  const result = await build({
    stdin: {
      contents: `import {getDocument,GlobalWorkerOptions,TextLayer} from ${JSON.stringify(join(root, "legacy/build/pdf.mjs"))};globalThis.__okamiPdfRuntime={getDocument,GlobalWorkerOptions,TextLayer};`,
      loader: "js",
      resolveDir: root,
    },
    bundle: true,
    minify: true,
    write: false,
    platform: "browser",
    format: "iife",
    target: ["chrome100", "safari15"],
    legalComments: "inline",
    logLevel: "silent",
  });
  const runtime = result.outputFiles[0].contents;
  const worker = await readFile(join(root, "legacy/build/pdf.worker.min.mjs"));
  const id = createHash("sha256")
    .update(version)
    .update(runtime)
    .update(worker)
    .digest("hex")
    .slice(0, 16);
  const prefix = `/_expo/static/pdf-reader/${version}-${id}/`;
  const output = join(publicRoot, `${version}-${id}`);
  await rm(publicRoot, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  await writeFile(join(output, "runtime.js"), runtime);
  await writeFile(join(output, "worker.mjs"), worker);
  for (const name of ["cmaps", "standard_fonts", "wasm"])
    await cp(join(root, name), join(output, name), { recursive: true });
  await cp(join(root, "LICENSE"), join(output, "LICENSE"));
  const manifest = `// Generated by scripts/bundle-pdf-reader.mjs; API and worker versions must match.\nexport const PDF_READER_ASSET_ROOT = ${JSON.stringify(prefix)};\n`;
  if (manifestPath) await writeFile(manifestPath, manifest);
  return { prefix, version, runtimeBytes: runtime.length, workerBytes: worker.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await bundlePdfReader();
  console.log(
    `Bundled lazy PDF reader ${result.version} (${result.runtimeBytes} runtime bytes; ${result.workerBytes} worker bytes).`,
  );
}
